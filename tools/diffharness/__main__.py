"""Runs the differential harness and writes docs/verification.md.

    $env:PYTHONPATH = "analysis/tools/python;tools"
    python -m diffharness                 # all functions, 200 cases each
    python -m diffharness -n 50 rand8     # some functions, fewer cases, no report
"""
import argparse
import sys
import time
from datetime import datetime, timezone

from .cases import SPECS, bind
from .harness import ROOT, Harness

REPORT = ROOT / 'docs/verification.md'


def main() -> int:
    p = argparse.ArgumentParser(prog='python -m diffharness', description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('names', nargs='*', help='functions to run (default: all)')
    p.add_argument('-n', type=int, default=200, help='cases per function (default 200)')
    p.add_argument('--seed', type=int, default=1)
    p.add_argument('--no-report', action='store_true', help='do not write docs/verification.md')
    a = p.parse_args()

    specs = [s for s in SPECS if not a.names or s.name in a.names]
    unknown = set(a.names) - {s.name for s in specs}
    if unknown:
        p.error(f'unknown function(s): {", ".join(sorted(unknown))}')
    h = Harness()
    bind(h)
    rows, failed = [], 0
    for spec in specs:
        t0 = time.perf_counter()
        results = h.run(spec, a.n, a.seed)
        dt = time.perf_counter() - t0
        ok = sum(r.ok for r in results)
        errors = [r for r in results if r.error]
        bad = [r for r in results if not r.ok and not r.error]
        failed += len(results) - ok
        first = (errors or bad or [None])[0]
        detail = '' if first is None else (f'{first.label}: ' if first.label else '') + (first.error or '; '.join(first.problems))
        changed = sum(r.changed for r in results) / max(1, len(results))
        rows.append((spec, len(results), ok, len(bad), len(errors), changed, dt, detail))
        print(f'{spec.name:14} {spec.addr}  {ok}/{len(results)} match  {len(bad)} differ  {len(errors)} errors'
              f'  {dt:5.1f}s  {detail}', flush=True)

    if not a.names and not a.no_report:
        write_report(rows, a.n, a.seed)
        print(f'wrote {REPORT.relative_to(ROOT)}')
    return 1 if failed else 0


def write_report(rows, n, seed):
    when = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    lines = [
        '# Verification results',
        '',
        f'Generated by `python -m diffharness` on {when}, {n} cases per function, seed {seed}. '
        'This file is overwritten on every full run.',
        '',
        'Each case runs the original function under Unicorn and the port\'s C function on the same memory '
        'snapshot. A case matches when the returned registers and every changed memory byte agree. '
        'The original\'s own stack frame, flags and untouched memory are not compared. '
        'A case with several calls (`sim_tick`) compares after every call and stops at the first one that differs. '
        'The `cga_` functions run TD2CGA\'s own graphics library against the port\'s CGA backend: the two sides '
        'keep their state at different addresses, so each case writes the same buffer and sprite into both '
        'memories and compares only those bytes.',
        '',
        '| Function | Original | Inputs | Cases | Match | Differ | Errors | Bytes changed per case | First problem |',
        '|---|---|---|---:|---:|---:|---:|---:|---|',
    ]
    for spec, total, ok, bad, err, changed, _, detail in rows:
        lines.append(f'| `{spec.name}` | `{spec.addr}` | {spec.note} | {total} | {ok} | {bad} | {err} | '
                     f'{changed:.0f} | {detail.replace("|", "/") or "none"} |')
    lines.append('')
    REPORT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    sys.exit(main())
